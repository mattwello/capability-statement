// Build: QR code → render HTML in Chromium → A4 PDF + 300 dpi PNG previews → QA report.
//   npm install && npm run build
import { chromium } from "playwright";
import QRCode from "qrcode";
import jsQR from "jsqr";
import { PNG } from "pngjs";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "src");
const OUT = path.join(ROOT, "output");
const PREV = path.join(OUT, "previews");
const WEBSITE = "https://www.westcoastenergy.com.au";
const PDF_NAME = "Westcoast-Energy_Property-Management_Capability-Statement_A4.pdf";
const PDF_WEB_NAME = "Westcoast-Energy_Property-Management_Capability-Statement_A4_email.pdf";
const PAGE_NAMES = ["01-Cover", "02-About-and-Capabilities", "03-Property-Management-Partnerships", "04-Our-Work-and-Contact"];
const SCALE = 300 / 96; // 300 dpi previews

fs.mkdirSync(path.join(SRC, "generated"), { recursive: true });
fs.mkdirSync(PREV, { recursive: true });

// 1 — QR code (vector, brand navy, error-correction level Q)
const qrSvg = await QRCode.toString(WEBSITE, {
  type: "svg", errorCorrectionLevel: "Q", margin: 0,
  color: { dark: "#1B2B38", light: "#FFFFFF00" },
});
fs.writeFileSync(path.join(SRC, "generated", "qr-website.svg"), qrSvg);

// 1b — Auto-discover assets: assets/photos/<slot>.(jpg|jpeg|png|webp) and assets/logo/*.(png|svg|jpg|webp)
const IMG = /\.(jpe?g|png|webp|svg)$/i;
const list = (d) => (fs.existsSync(d) ? fs.readdirSync(d).filter((f) => IMG.test(f)).sort() : []);
const auto = { photos: {}, logo: null };
for (const f of list(path.join(ROOT, "assets", "photos"))) auto.photos[f.replace(IMG, "")] = `../assets/photos/${f}`;
const logos = list(path.join(ROOT, "assets", "logo"));
if (logos.length) auto.logo = `../assets/logo/${logos.find((f) => /\.svg$/i.test(f)) || logos[0]}`;
fs.writeFileSync(path.join(SRC, "generated", "auto-assets.js"),
  `// Generated by scripts/build.mjs — do not edit. Explicit entries in assets-map.js take priority.\nwindow.WCE_AUTO = ${JSON.stringify(auto, null, 2)};\n`);

// 2 — Render
const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: SCALE, viewport: { width: 900, height: 1200 } });
const warnings = [];
page.on("console", (m) => { if (m.type() === "error") warnings.push(`console: ${m.text()}`); });
page.on("requestfailed", (r) => warnings.push(`failed to load: ${r.url()}`));

await page.goto(pathToFileURL(path.join(SRC, "index.html")).href);
await page.waitForFunction(() => window.__WCE_READY === true, null, { timeout: 30000 });
await page.emulateMedia({ media: "print" });

// 3 — QA: text overflow, text-on-text collisions, safe margins
const qa = await page.evaluate(() => {
  const mm = 96 / 25.4;
  const out = [];
  const textSel = ".display, p, .h-item, .kicker, .tbc, .v, .h, .t, .d, .n, .no, .title, .place, .edition, .base, .folio, .scan, .co, .k, .r, .note, .caps span, .ph-label";
  document.querySelectorAll(".page").forEach((pg, i) => {
    const P = pg.getBoundingClientRect();
    const els = [...pg.querySelectorAll(textSel)].filter((e) => e.getClientRects().length);
    const boxes = els.map((e) => {
      const r = document.createRange(); r.selectNodeContents(e);
      const b = r.getBoundingClientRect();
      return { e, x0: (b.left - P.left) / mm, y0: (b.top - P.top) / mm, x1: (b.right - P.left) / mm, y1: (b.bottom - P.top) / mm };
    });
    for (const b of boxes) {
      const name = (b.e.className || b.e.tagName) + ` "${b.e.textContent.trim().slice(0, 32)}"`;
      if (b.e.classList.contains("ph-label")) continue;
      if (b.x0 < 7.5 || b.y0 < 7.5 || b.x1 > 202.5 || b.y1 > 289.5)
        out.push(`p${i + 1}: inside 7.5mm safe margin → ${name} [${b.x0.toFixed(1)},${b.y0.toFixed(1)} – ${b.x1.toFixed(1)},${b.y1.toFixed(1)}]`);
    }
    for (let a = 0; a < boxes.length; a++) for (let c = a + 1; c < boxes.length; c++) {
      const A = boxes[a], C = boxes[c];
      if (A.e.contains(C.e) || C.e.contains(A.e)) continue;
      if (A.e.classList.contains("ph-label") || C.e.classList.contains("ph-label")) continue;
      const ix = Math.min(A.x1, C.x1) - Math.max(A.x0, C.x0), iy = Math.min(A.y1, C.y1) - Math.max(A.y0, C.y0);
      if (ix > 0.3 && iy > 0.3) out.push(`p${i + 1}: text overlap "${A.e.textContent.trim().slice(0, 24)}" × "${C.e.textContent.trim().slice(0, 24)}"`);
    }
  });
  return { issues: out, missing: window.__WCE_MISSING };
});

// 4 — PDF (vector text, exact A4)
const pdfPath = path.join(OUT, PDF_NAME);
await page.pdf({ path: pdfPath, preferCSSPageSize: true, printBackground: true });

// 5 — PNG previews at 300 dpi
const pages = await page.$$(".page");
const pngs = [];
for (let i = 0; i < pages.length; i++) {
  const f = path.join(PREV, `Westcoast-Energy_Capability-Statement_Page-${PAGE_NAMES[i]}.png`);
  await pages[i].screenshot({ path: f });
  pngs.push(f);
}

// 6 — Verify the QR actually scans to the website (decoded from the rendered page)
const qrShot = await (await page.$("#qr")).screenshot({ omitBackground: false });

// 6b — Email-size PDF (identical layout, lighter photo copies)
await page.goto(pathToFileURL(path.join(SRC, "index.html")).href + "?web");
await page.waitForFunction(() => window.__WCE_READY === true, null, { timeout: 30000 });
await page.emulateMedia({ media: "print" });
const pdfWebPath = path.join(OUT, PDF_WEB_NAME);
await page.pdf({ path: pdfWebPath, preferCSSPageSize: true, printBackground: true });
const img = PNG.sync.read(qrShot);
const pad = 40, W = img.width + pad * 2, H = img.height + pad * 2;
const rgba = new Uint8ClampedArray(W * H * 4).fill(255);
for (let y = 0; y < img.height; y++) for (let x = 0; x < img.width; x++) {
  const s = (y * img.width + x) * 4, d = ((y + pad) * W + (x + pad)) * 4;
  rgba.set(img.data.subarray(s, s + 4), d);
}
const decoded = jsQR(rgba, W, H);
await browser.close();

// 7 — Report
const pdfBytes = fs.readFileSync(pdfPath);
const pageCount = (pdfBytes.toString("latin1").match(/\/Type\s*\/Page[^s]/g) || []).length;
const box = pdfBytes.toString("latin1").match(/\/MediaBox\s*\[\s*0 0 ([\d.]+) ([\d.]+)\]/);
console.log(`\nPDF      ${path.relative(ROOT, pdfPath)}  (${(pdfBytes.length / 1024 / 1024).toFixed(2)} MB, ${pageCount} pages, MediaBox ${box ? `${box[1]}×${box[2]} pt` : "?"} — A4 is 595.28×841.89)`);
console.log(`PDF      ${path.relative(ROOT, pdfWebPath)}  (${(fs.statSync(pdfWebPath).size / 1024 / 1024).toFixed(2)} MB, email size)`);
pngs.forEach((f) => console.log(`PNG      ${path.relative(ROOT, f)}`));
console.log(`QR       ${decoded ? `decodes to ${decoded.data} ${decoded.data === WEBSITE ? "✓" : "✗ MISMATCH"}` : "✗ could not decode"}`);
console.log(`Assets   ${qa.missing.length ? `${qa.missing.length} slot(s) still placeholders: ${qa.missing.join(", ")}` : "all photo slots and logo filled ✓"}`);
console.log(`Layout   ${qa.issues.length ? "" : "no text overlaps, all text inside safe margins ✓"}`);
qa.issues.forEach((m) => console.log("  ! " + m));
warnings.forEach((m) => console.log("  ! " + m));
